"""Generate firmware/main/assets.h: boot splash JPEG + anti-aliased ASCII fonts.

Run: uv run --with pillow python tools/gen_firmware_assets.py
"""
import io
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "tools"))
from gen_logo import CREAM, INK as DARK, LIME, draw_mark  # noqa: E402

out = ["// Generated by tools/gen_firmware_assets.py. Do not edit.", "#pragma once", "#include <stdint.h>", ""]


def c_bytes(data):
    return ",".join(f"0x{b:02x}" for b in data)


# Splash: logo mark above the "OpenDeck" name, drawn 4x and scaled down.
SS = 4
W, H = 240, 168
pad = Image.new("RGB", (W * SS, H * SS), DARK)
d = ImageDraw.Draw(pad)
mark = 104 * SS
draw_mark(d, (pad.width - mark) / 2, 4 * SS, mark, LIME, CREAM)
title = ImageFont.truetype(str(root / "assets/fonts/Unbounded-SemiBold.ttf"), 30 * SS)
d.text((pad.width / 2, (4 + 104 + 18) * SS), "OpenDeck", font=title, fill=CREAM, anchor="mt")
pad = pad.resize((W, H), Image.LANCZOS)
buf = io.BytesIO()
pad.save(buf, "JPEG", quality=90)
data = buf.getvalue()
out += [f"#define SPLASH_W {pad.width}", f"#define SPLASH_H {pad.height}",
        f"static const uint8_t SPLASH[{len(data)}] = {{{c_bytes(data)}}};", ""]


# Fonts: 4 bits per pixel coverage, rows packed high nibble first.
def gen_font(name, ttf, size):
    font = ImageFont.truetype(str(ttf), size)
    ascent, descent = font.getmetrics()
    glyphs, blob = [], bytearray()
    for code in range(32, 127):
        ch = chr(code)
        adv = round(font.getlength(ch))
        l, t, r, b = font.getbbox(ch)
        w, h = max(0, r - l), max(0, b - t)
        off = len(blob)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255)
            px = im.load()
            for y in range(h):
                for x in range(0, w, 2):
                    a = px[x, y] >> 4
                    bb = (px[x + 1, y] >> 4) if x + 1 < w else 0
                    blob.append((a << 4) | bb)
        glyphs.append((off, w, h, l, t, adv))
    rows = ",".join(f"{{{o},{w},{h},{x},{y},{a}}}" for o, w, h, x, y, a in glyphs)
    return [f"static const uint8_t {name}_BITS[{len(blob)}] = {{{c_bytes(blob)}}};",
            f"static const font_glyph_t {name}_GLYPHS[95] = {{{rows}}};",
            f"static const font_t {name} = {{{name}_BITS, {name}_GLYPHS, {ascent + descent}, {ascent}}};", ""]


out += ["typedef struct { uint32_t off; uint8_t w, h; int8_t x, y; uint8_t adv; } font_glyph_t;",
        "typedef struct { const uint8_t *bits; const font_glyph_t *glyphs; uint8_t line_h, ascent; } font_t;", ""]
out += gen_font("FONT_BODY", root / "assets/fonts/Lexend-Medium.ttf", 15)
out += gen_font("FONT_BIG", root / "assets/fonts/Lexend-SemiBold.ttf", 24)

dst = root / "firmware/main/assets.h"
dst.write_text("\n".join(out) + "\n")
print(dst, "splash", pad.size, len(data), "bytes")
